import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { once } from 'node:events';
import path from 'node:path';
import { WebSocket, WebSocketServer } from 'ws';
import { sendDeliveredChat } from '../src/review-delivery.ts';
import { readReviewCaptures } from '../src/review-capture.ts';
const root = await mkdtemp(path.resolve('.agents/scratchpads/landing-20261006/review-delivery-'));
const file = path.join(root, 'reviews.json'), server = new WebSocketServer({ port: 0, host: '127.0.0.1' });
await once(server, 'listening');
const connected = once(server, 'connection');
const client = new WebSocket(`ws://127.0.0.1:${server.address().port}`);
const [socket] = await connected;
await once(client, 'open');
const received = []; client.on('message', data => received.push(JSON.parse(String(data))));
let invalidations = 0, failures = 0;
const options = { file, onCaptured: () => invalidations++, onError: () => failures++ };
const identity = { adapter: 'native', agentId: 'agent-a', sessionId: 'session-a', by: 'Synthetic A' };
const text = (id, url) => ({ t: 'text', id, text: `Open ${url}`, at: Date.now() - 100 });
const wait = async predicate => { const end = Date.now() + 3000; while (!(await predicate())) { if (Date.now() > end) throw Error('Delivery condition not reached'); await new Promise(r => setTimeout(r, 15)); } };
try {
  sendDeliveredChat(socket, { t: 'hello', session: 'session-a', log: [text('m1','https://review.test/one'), text('m2','https://review.test/two'), {t:'user',id:'u1',text:'https://private.test/user',at:Date.now()}] }, identity, options);
  await wait(async () => (await readReviewCaptures(file)).length === 2 && received[0]?.t === 'hello' && invalidations === 1);
  assert.equal(received[0].t, 'hello'); assert.equal(invalidations, 1);
  sendDeliveredChat(socket, {t:'older',events:[text('m1','https://review.test/one')]}, identity, options);
  sendDeliveredChat(socket, {t:'delta',id:'partial',text:'https://private.test/partial'}, identity, options);
  sendDeliveredChat(socket, {...text('child','https://private.test/child'),parent:'another-agent'}, identity, options);
  sendDeliveredChat(socket, text('unbound','https://private.test/unbound'), {...identity,sessionId:null}, options);
  sendDeliveredChat(socket, text('session-b','https://review.test/session-b'), {...identity,sessionId:'session-b'}, options);
  const frozen = {...identity,adapter:'legacy',agentId:'agent-b',sessionId:'legacy-session',by:'Synthetic B'};
  sendDeliveredChat(socket, text('legacy','https://review.test/legacy'), frozen, options);
  frozen.sessionId = 'WRONG-SESSION'; frozen.by = 'WRONG-AGENT';
  await wait(async () => (await readReviewCaptures(file)).length === 4);
  const rows = await readReviewCaptures(file);
  assert.deepEqual(rows.map(r => r.url).sort(), ['https://review.test/one','https://review.test/two','https://review.test/session-b','https://review.test/legacy'].sort());
  assert.equal(rows.find(r=>r.url.endsWith('/legacy')).provenance.sessionId,'legacy-session');
  assert.equal(rows.find(r=>r.url.endsWith('/legacy')).agent,'Synthetic B');
  assert.equal(rows.find(r=>r.url.endsWith('/session-b')).provenance.sessionId,'session-b');
  assert.ok(received.some(r=>r.t==='older'));
  let fakeSends=0;
  const failedSocket={OPEN:1,readyState:1,send:(_data,callback)=>{fakeSends++;callback(new Error('Synthetic write failure'));}};
  sendDeliveredChat(failedSocket,text('failed','https://private.test/failed'),identity,options);
  failedSocket.readyState=3;sendDeliveredChat(failedSocket,text('closed','https://private.test/closed'),identity,options);
  assert.equal(fakeSends,1);assert.equal((await readReviewCaptures(file)).length,4);assert.equal(failures,0);
  console.log('PASS: actual socket delivery, both hello replies, older replay deduplication, native/legacy provenance, frozen session identity, exclusions, failed/closed socket, cache invalidation.');
} finally { client.close();socket.close();await new Promise(resolve=>server.close(resolve)); }
